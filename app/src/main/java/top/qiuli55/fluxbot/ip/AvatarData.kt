    fun shape(key: String?): Shape = shapes.firstOrNull { it.key == key } ?: shapes[4]

    fun palette(key: String?): Palette = palettes.firstOrNull { it.key == key } ?: palettes[9]

    fun shapeFromSeed(seed: String): String = shapes[(hashSeed(seed) % shapes.size + shapes.size) % shapes.size].key

    fun paletteFromSeed(seed: String): String =
        palettes[(hashSeed("$seed-palette") % palettes.size + palettes.size) % palettes.size].key

    fun hashSeed(text: String?): Int {
        var h = 2166136261L
        val s = text?.takeIf { it.isNotEmpty() } ?: "flo"
        for (ch in s) {
            h = h xor ch.code.toLong()
            h = (h * 16777619L) and 0xFFFFFFFFL
        }
        return (h and 0x7FFFFFFFL).toInt()
    }
